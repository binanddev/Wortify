import fs from 'node:fs/promises';
import path from 'node:path';
import postcss from 'postcss';
const root=path.resolve(import.meta.dirname,'..');
const destination=path.join(root,'src/vendor/retro-libraries.css');
const scope=':root[data-interface="retro"]';
const output=postcss.root();
output.append(postcss.comment({text:'Generated by scripts/build-retro-vendor.mjs. NES.css 2.3.0 (MIT), RPGUI 1.0.3 (Zlib). Scoped, selected CSS only; no external fonts or DOM-mutating scripts.'}));
for(const [pkg,file] of [['nes.css','css/nes.css'],['rpgui','rpgui.css']]){
 const source=path.join(root,'node_modules',pkg,file);
 const ast=postcss.parse(await fs.readFile(source,'utf8'));
 ast.walkRules(rule=>{
   const allowed=pkg==='nes.css'? /\.nes-(btn|container|balloon|icon|progress)\b/.test(rule.selector): /\.rpgui-container\.framed/.test(rule.selector);
   if(!allowed)return;
   const copy=rule.clone();
   copy.selector=copy.selectors.map(sel=>{
     if(pkg==='nes.css')sel=sel.replace(/\.nes-btn\b/g,':is(.nes-btn,.btn)').replace(/\.is-primary\b/g,':is(.is-primary,.primary)');
     else sel=sel.replace('.rpgui-container.framed-golden-2',':is(.rpgui-container.framed-golden-2,.nav-face)')
       .replace('.rpgui-container.framed-grey',':is(.rpgui-container.framed-grey,.author-panel)')
       .replace('.rpgui-container.framed-golden',':is(.rpgui-container.framed-golden,.work-paper,.flip-face,[role="dialog"])')
       .replace('.rpgui-container.framed',':is(.rpgui-container.framed,.glass,.catalog-card,.profile-panel,.library-card)');
     return scope+' '+sel;
   }).join(',\n');
   copy.walkDecls(d=>{d.value=d.value.replace(/url\(["']?([^)'"\s]+)["']?\)/g,(all,url)=>{
     if(/^(data:|https?:|#)/.test(url))return all;
     return `url("${path.relative(path.dirname(destination),path.resolve(path.dirname(source),url)).replaceAll('\\','/')}")`;
   });});
   let wrapped=copy;
   for(let parent=rule.parent;parent && parent.type!=='root';parent=parent.parent){
     if(parent.type==='atrule'){ const outer=parent.clone({nodes:[]});outer.append(wrapped);wrapped=outer; }
   }
   output.append(wrapped);
 });
}
const cursors=postcss.rule({selector:scope});
for(const name of ['default','point','select','grab-open']){
 const data=await fs.readFile(path.join(root,'node_modules/rpgui/img/cursor',name+'.png'));
 cursors.append({prop:'--retro-cursor-'+name,value:'url("data:image/png;base64,'+data.toString('base64')+'")'});
}
output.append(cursors);
await fs.mkdir(path.dirname(destination),{recursive:true});
await fs.writeFile(destination,output.toString());
console.log('Generated isolated Retro library styles');
